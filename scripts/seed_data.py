def gen_products(n: int = 600) -> list[dict]:
    """Return the curated catalog (kept sliceable for callers)."""
    return [dict(p, specs=dict(p["specs"])) for p in PRODUCTS[:n]]


def main() -> None:
    products = gen_products()
    with open("data_seed.json", "w") as f:
        json.dump(products, f, indent=1)
    with_img = sum(1 for p in products if p["image_urls"])
    print(f"seeded {len(products)} products ({with_img} with photos) -> data_seed.json")


